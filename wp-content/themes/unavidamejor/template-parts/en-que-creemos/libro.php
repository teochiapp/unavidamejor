      <!-- Página 2: La Palabra de Dios -->
      <div class="page magazine-page" data-index="1" data-block="1">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">La Palabra de Dios</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que la Biblia es la Palabra de Dios. Toda la Escritura, tanto el Antiguo como el Nuevo Testamento, son la Palabra inspirada de Dios <span class="biblical-citation">(2 Timoteo 3:16-17)</span>. Contienen la revelación completa de Dios para la Salvación del Ser humano. Reconocemos a la Biblia como autoridad final para el ejercicio de la fe y la conducta cristiana.</p>
          </div>
        </div>
      </div>

      <!-- Página 3: El Dios Trino -->
      <div class="page magazine-page" data-index="2" data-block="1">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">El Dios Trino</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos en un solo Dios <span class="biblical-citation">(Deuteronomio 6:4)</span>, creador de todas las cosas. Quien es Uno y Trino <span class="biblical-citation">(Tito 3:4-6)</span>. El cual existe eternamente en tres personas: Dios Padre, Dios Hijo Jesucristo y Dios Espíritu Santo. Creemos que Jesucristo es el Hijo de Dios, Mesías prometido al mundo que fue concebido por el poder del Espíritu Santo en el vientre virgen de María <span class="biblical-citation">(Gálatas 4:4; Mateo 1:18-25)</span>. Creemos que murió en una cruz, en sacrificio perfecto por nuestros pecados de acuerdo con las Escrituras <span class="biblical-citation">(1 Pedro 3:18; Filipenses 2:5-11)</span>. Que resucitó de entre los muertos y ascendió al cielo donde fue entronizado a la diestra del Padre en majestad, ejerciendo dominio y autoridad sobre toda la existencia <span class="biblical-citation">(Efesios 1:17-22)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 4: El Espíritu Santo -->
      <div class="page magazine-page" data-index="3" data-block="2">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">El Espíritu Santo</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que el Espíritu Santo es Dios. Su ministerio es el glorificar al Señor Jesucristo y hacer consciente de pecado y regenerar al pecador, llevándole a creer en Cristo. Bautizando al creyente dentro del cuerpo único que es la Iglesia <span class="biblical-citation">(Efesios 4:4-5)</span>, de quien Cristo es la cabeza <span class="biblical-citation">(Efesios 1:22-23)</span>. El Espíritu Santo mora, guía, instruye, llena y da poder al creyente para que lleve una vida consagrada y piadosa <span class="biblical-citation">(Juan 14:16)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 5: La Dignidad Humana -->
      <div class="page magazine-page" data-index="4" data-block="2">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">La Dignidad Humana</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que el ser humano, varón y mujer, fueron creados por Dios a su propia imagen, ambos sexos poseen la misma dignidad intrínseca que los constituye como imago Dei <span class="biblical-citation">(Génesis 1:27)</span>. Creemos en la dignidad de la vida de todos los seres humanos desde la concepción <span class="biblical-citation">(Salmos 139:13-16)</span> y hasta su muerte natural <span class="biblical-citation">(Éxodo 21:22-24)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 6: La Caída y la Redención -->
      <div class="page magazine-page" data-index="5" data-block="3">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">La Caída y la Redención</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que el ser humano cayó en pecado, transmitiéndolo a su descendencia <span class="biblical-citation">(Génesis 3)</span>. Toda la raza humana, por ello, está perdida <span class="biblical-citation">(Romanos 3:23)</span>, y sólo mediante el arrepentimiento, la fe en Jesucristo, y la regeneración del Espíritu Santo, puede obtenerse la salvación y vida eterna <span class="biblical-citation">(Romanos 3:23-26; 2 Timoteo 1:9-10)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 7: La Salvación por Gracia -->
      <div class="page magazine-page" data-index="6" data-block="3">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">La Salvación por Gracia</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que la muerte expiatoria de Jesucristo y su resurrección, sientan las únicas bases para la justificación y la salvación de todos los que creen, y que sólo aquellos que reciben a Jesucristo por fe, son nacidos del Espíritu Santo y sellados por Él hasta el día de la redención <span class="biblical-citation">(Juan 1:12-13; Efesios 4:30; 1 Pedro 1:20-23)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 8: El Regreso de Cristo -->
      <div class="page magazine-page" data-index="7" data-block="4">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">El Regreso de Cristo</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que Jesucristo regresará <span class="biblical-citation">(Hechos 1:10-11; Apocalipsis 22:20)</span>, y que la esperanza en Su retorno tiene una influencia vital en la vida personal y el servicio del creyente <span class="biblical-citation">(Hebreos 10:24-25)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 9: Resurrección y Juicio -->
      <div class="page magazine-page" data-index="8" data-block="4">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">Resurrección y Juicio</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos en la resurrección física de todos los muertos <span class="biblical-citation">(Hebreos 9:27)</span>, del creyente en Jesucristo a la bendición eterna y gozo con el Señor <span class="biblical-citation">(1 Corintios 15:12-20)</span>, y del no creyente al juicio y castigo consciente eterno <span class="biblical-citation">(Mateo 25:46)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 10: La Iglesia -->
      <div class="page magazine-page" data-index="9" data-block="5">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">La Iglesia</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que la Iglesia es el Cuerpo de Cristo <span class="biblical-citation">(Colosenses 1:18-19)</span>. Constituida por todas las personas que, mediante la fe en Jesucristo, han sido regeneradas por el Espíritu Santo y se unen en el Cuerpo de Cristo, del que Él es la cabeza <span class="biblical-citation">(Efesios 1:22; 4:4)</span>. La Iglesia se hace visible en expresiones comunitarias locales, constituyéndose cada una de ellas en agencias del Reino de Dios en la tierra, que trabajan cooperativamente en el desarrollo de su misión en el mundo <span class="biblical-citation">(Efesios 3:7-12; 1 Corintios 12:12-20)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 11: Ordenanzas de la Iglesia -->
      <div class="page magazine-page" data-index="10" data-block="5">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">Ordenanzas de la Iglesia</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que el bautismo en agua y la Cena del Señor, son ordenanzas a ser observadas por la Iglesia permanentemente, como un símbolo de gratitud y adoración, no como un medio de salvación <span class="biblical-citation">(Mateo 28:18-20; Mateo 26:17-30; Hechos 2:41-42)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 12: El Mundo Espiritual -->
      <div class="page magazine-page" data-index="11" data-block="6">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">El Mundo Espiritual</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos en la existencia de Satanás, los demonios y los ángeles como seres creados por Dios, pertenecientes al mundo espiritual que ejercen su influencia en el terrenal <span class="biblical-citation">(Efesios 6:10-12)</span>. Todos ellos seres creados por Dios y sujetos a su soberanía <span class="biblical-citation">(Job 2:1-17)</span>. Creemos que el rol de los ángeles es servir a los herederos de la salvación <span class="biblical-citation">(Hebreos 1:14)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 13: Victoria sobre Satanás -->
      <div class="page magazine-page" data-index="12" data-block="6">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">Victoria sobre Satanás</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos que el rol del diablo en esta era es oponerse a los ungidos (todos los creyentes en Cristo) <span class="biblical-citation">(2 Corintios 2:11; 1 Juan 3:7-10)</span>. Creemos que la iglesia tiene garantizada la victoria final sobre el diablo y sus ángeles en el presente a través de la oración, el testimonio y la Palabra <span class="biblical-citation">(Apocalipsis 12:10)</span>.</p>
          </div>
        </div>
      </div>

      <!-- Página 14: Dones Espirituales -->
      <div class="page magazine-page" data-index="13" data-block="7">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">Dones Espirituales</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos en la vigencia de todos los dones espirituales <span class="biblical-citation">(Romanos 12:6-9; 1 Corintios 12:4-11)</span> y de todas las funciones delegadas por Cristo a la iglesia <span class="biblical-citation">(Efesios 4:11)</span> como herramientas eficaces para llevar adelante la misión de la iglesia en el mundo.</p>
          </div>
        </div>
      </div>

      <!-- Página 15: El Diseño Divino de la Familia -->
      <div class="page magazine-page" data-index="14" data-block="7">
        <div class="page-content">
          <div class="page-header">
            <div class="page-title">El Diseño Divino de la Familia</div>
          </div>
          <div class="belief-section">
            <p class="belief-text">Creemos en la familia de acuerdo con el diseño de Dios. Constituida por un hombre y una mujer unidos en matrimonio heterosexual, monógamo <span class="biblical-citation">(Génesis 2:24)</span>. Creemos que la familia es el código de ética social por excelencia y núcleo fundamental sobre el cual se debe articular la sociedad.</p>
          </div>
